class Solution:
    def maxProduct(self, nums: list[int]) -> int:
        result = float("-inf")
        cur_max = cur_min = 1
        for n in nums:
            a, b, c = n, n * cur_max, n * cur_min
            cur_max, cur_min = max(a, b, c), min(a, b, c)
            result = max(result, cur_max)
        return result


